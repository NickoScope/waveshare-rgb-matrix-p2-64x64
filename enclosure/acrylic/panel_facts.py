VENT_SLOT_W = P(2.0, SPEC, "ширина щели")
VENT_LONG = P(26.0, SPEC, "длинная щель")
VENT_GAP = P(2.0, SPEC, "между щелями в ряду")
VENT_ROWS = P(2, SPEC)
VENT_ROW_GAP = P(2.0, SPEC, "между рядами")
VENT_CLEAR_TOP = P(2.5, SPEC, "от верхнего ряда до паза борта")
VENT_CLEAR_X = P(2.5, SPEC, "вокруг стоек и боковых пазов")


def unmeasured():
    return [(v, n) for v, s, n in _facts if s == MEAS]


if __name__ == "__main__":
    # панель утоплена заподлицо, поэтому передняя плита в стопку НЕ входит
    depth_min = PANEL_T + max(CONN_H, VH4_H, CTRL_T) + T
    print(f"поле        {FIELD_W:.1f} x {FIELD_H:.1f}")
    print(f"корпус      {CASE_W:.1f} x {CASE_H:.1f}")
    print(f"окно        {WINDOW_W:.1f} x {WINDOW_H:.1f}  (панели заподлицо)")
    print(f"глубина: матрица {PANEL_T} (её первые {T} внутри передней плиты) + "
          f"навесное {max(CONN_H, VH4_H, CTRL_T)} + задняя {T} = {depth_min:.1f}")
    print(f"  было бы при панели ЗА плитой: {T + depth_min:.1f}")
    print(f"\nна обмере: {len(unmeasured())}")
    for v, n in unmeasured():
        print(f"  {str(v):>8}  {n}")
