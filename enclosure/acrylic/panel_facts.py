# -*- coding: utf-8 -*-
"""
Факты о железе для акрилового корпуса. У каждого числа — источник.

Те же три метки, что в соседнем FDM-проекте (../cad/case_c_lib.py), чтобы
не плодить словарей:

    ЧЕРТЁЖ — прочитано с заводского чертежа, см. ../../docs/10-mechanical.md
    ТЗ     — решение из задания ../TZ_KORPUS_C_LED_MATRIX_RU.md
    ОБМЕР  — догадка, ждёт замера на живом железе

Правило простое: ничего с меткой ОБМЕР не уходит в файл на резку.
Список печатается при запуске этого файла.
"""

DWG, SPEC, MEAS = "ЧЕРТЁЖ", "ТЗ", "ОБМЕР"
FACT = "ЗАМЕР"          # подтверждено на живом железе, Николай 25.09.2026
_facts = []


def P(value, src, note=""):
    _facts.append((value, src, note))
    return value


# ── матрица ────────────────────────────────────────────────────────────────
# Ловушка, из-за которой и написан весь §4.1 задания: паспорт даёт 128 x 128,
# а чертёж размеряет ЛИТУЮ РАМКУ как 127.8 и подписывает её "bottom case".
# Кромку самой платы чертёж не размеряет вовсе. Если наружу выступает рамка,
# две матрицы вплотную дают 255.6, и шаг через стык выходит 1.8 вместо 2.0 —
# на 10 % короче, и это видно с обычного расстояния.
PANEL_FRAME = P(127.8, DWG, "литая рамка, подписана JXS-P2-128*128 bottom case")
PANEL_BOARD = P(128.0, FACT, "кромка платы; чертёж её не размеряет, подтверждено замером")
PANEL_T = P(15.0, FACT, "толщина модуля целиком; на листе не размерена")
PITCH = P(2.0, SPEC, "шаг пикселя")
PIXELS = P(64, SPEC)

# Шесть точек M3 на матрицу, извлечены из слоя SCREW повторно 2026-09-10.
# Относительно центра детали. Полный размах 113.7 в обе стороны.
MOUNT_XY = P([(0.0, 56.85), (0.0, -56.85),
              (-56.85, 44.0), (56.85, 44.0),
              (-56.85, -44.0), (56.85, -44.0)], DWG, "шесть M3, слой SCREW")
MOUNT_D = P(2.5, DWG, "отверстие под M3 в литой рамке")

# ── поле из двух матриц ────────────────────────────────────────────────────
PANELS_N = P(2, SPEC)
FIELD_W = P(PIXELS * PANELS_N * PITCH, SPEC, "256.0 при шаге 2.0")
FIELD_H = P(PIXELS * PITCH, SPEC, "128.0")

# ── контроллер и органы ────────────────────────────────────────────────────
CTRL_W = P(50.0, SPEC, "Waveshare ESP32-S3-RGB-Matrix")
CTRL_H = P(42.0, SPEC)
CTRL_T = P(9.0, FACT, "высота платы с надетыми разъёмами")
# Эти четыре точки я поставил САМ, симметрично, потому что Waveshare их не
# размеряет ни одной цифрой. «Замеры правильные» на них не распространяется:
# подтверждать надо не моё число, а то, что стоит на плате. Сверить шаг по
# обеим осям штангенциркулем.
CTRL_MOUNT = P([(-22.0, -18.0), (22.0, -18.0), (-22.0, 18.0), (22.0, 18.0)], MEAS,
               "крепёж контроллера: числа ПРИДУМАНЫ мной, Waveshare не размеряет")
CTRL_SCREW_D = P(2.6, SPEC, "под M2.5")
USB_W = P(9.5, SPEC, "окно под USB-C с запасом")
USB_H = P(4.5, SPEC)
CONN_H = P(9.0, FACT, "колодка HUB75 над задней плоскостью")
VH4_H = P(7.0, FACT, "колодка питания VH4")

ENC_HOLE_D = P(7.4, SPEC, "втулка M7 плюс 0.4")
ENC_KNOB_D = P(14.0, SPEC, "ручка; больше в свободную полосу не встанет")
ENC_FROM_RIGHT = P(26.0, SPEC, "энкодер справа в полосе, указание заказчика")

# ── динамик: тот же, что на NickoScope32 ───────────────────────────────────
# Visaton FRWS 5 SC, арт. 2220. Числа с ОФИЦИАЛЬНОГО каталожного листа
# (чертёж от 08.02.08): рамка 50 x 50 квадратная, четыре отверстия ⌀3.5 ПО
# УГЛАМ с шагом 44, посадочный вырез ⌀45, глубина за фланцем 23, фланец 4,
# магнит ⌀22, масса 52 г. В обычном паспорте чертежа НЕТ.
SPK_FLANGE = P(50.0, SPEC, "сторона квадратной рамки, Visaton FRWS 5 SC")
SPK_CUTOUT = P(45.0, SPEC, "вырез в панели")
SPK_BOLT_PITCH = P(44.0, SPEC, "шаг отверстий, по квадрату")
SPK_BOLT_D = P(3.5, SPEC)
# Полная высота динамика — ЗАМЕР Николая на живой детали, 28.0. Паспорт
# Visaton даёт 23 за фланцем, дистрибьютор 27 общей высоты; замер говорит 28,
# и он главнее обоих.
SPK_TOTAL = P(28.0, DWG, "полная высота, ЗАМЕР на живой детали 25.09.2026")
SPK_FLANGE_T = P(4.0, SPEC, "толщина фланца, с чертежа Visaton")
SPK_DEPTH_IN = P(SPK_TOTAL - SPK_FLANGE_T, SPEC, "за фланцем")
SPK_MAGNET_D = P(22.0, SPEC, "магнит, с чертежа Visaton")
# Окно под магнит в ЗАДНЕЙ плите. Динамик заходит в её толщину на 3 мм и
# кончается за 1 мм до наружной грани — наружу ничего не торчит, плита
# снаружи ровная. На этой глубине (25…28 из 28) это уже сам магнит ⌀22,
# а не конус корзины, поэтому 26 — это 22 плюс по 2 на сторону.
SPK_RELIEF_D = P(26.0, SPEC, "окно под магнит в задней плите: ⌀22 + 2 на сторону")

# ── точечная сетка: решётка динамика и надписи ─────────────────────────────
# Одна сетка на то и другое, чтобы читалось как одно пиксельное поле —
# по мотивам самой матрицы.
# Шаг 3.2 выбран не на глаз: при нём строка "NickoScope Matrix" минимальным
# шрифтом 4x6 выходит ровно 80 x 3.2 = 256.0 мм, то есть ТОЧНО в ширину
# экрана. И 80 колонок укладываются в 128 — столько же, сколько пикселей
# поперёк нашего табло, так что надпись помещается и на само табло.
#
# Совместить сетку с ПИКСЕЛЬНОЙ сеткой экрана один в один нельзя: у матрицы
# шаг 2.0, и при дырке ⌀2 перемычки не остаётся вовсе — ряд стал бы щелью.
DOT_D = P(2.0, SPEC, "отверстие сетки")
DOT_PITCH = P(3.2, SPEC, "перемычка 1.2 мм; строка = ровно ширина экрана")

# ── корпус ─────────────────────────────────────────────────────────────────
# Отсюда начинается собственно акриловый вариант. Числа взяты по образцу
# корпуса NickoScope32 v1b, где эта конструкция уже прошла проверку.
T = P(4.0, SPEC, "акрил 4 мм, как на NickoScope32")
# Рамка ужата до минимума. Предел задаёт не вкус, а паз под шип борта:
# борт утоплен на WALL_INSET и сам толщиной T, то есть паз занимает полосу
# 4…8 мм от кромки. Между пазом и окном нужен акрил — берём 3 мм.
#     рамка = утопление 4 + борт 4 + перемычка 3 = 11
BEZEL_WEB = P(3.0, SPEC, "перемычка между пазом борта и окном")
BEZEL_SIDE = P(11.0, SPEC, "минимум: WALL_INSET + T + BEZEL_WEB")
BEZEL_TOP = P(11.0, SPEC)
STRIP_H = P(20.0, SPEC, "свободная полоса снизу под энкодер, ТЗ §4.4")

# Панели УТОПЛЕНЫ в окно и стоят заподлицо с лицом передней плиты. Поэтому
# её 4 мм не добавляются к глубине, а занимаются первыми 4 мм самой матрицы.
WINDOW_GAP = P(0.3, SPEC, "зазор окна вокруг панели на сторону")
WINDOW_W = P(PANEL_BOARD * PANELS_N + 2 * WINDOW_GAP, SPEC)
WINDOW_H = P(PANEL_BOARD + 2 * WINDOW_GAP, SPEC)

# Колонка справа под динамик и энкодер
COL_GAP = P(6.0, SPEC, "от окна до фланца динамика, ужато с 12")
COL_W = P(SPK_FLANGE, SPEC)

# Полоса надписей под экраном, той же сеткой
TEXT_ROWS = P(6, SPEC, "одна строка шрифтом 4x6")
BAND_H = P(TEXT_ROWS * DOT_PITCH, SPEC)
BAND_GAP = P(5.0, SPEC, "от окна до строки, ужато с 8")
BEZEL_BOTTOM = P(11.0, SPEC)

CASE_W = P(BEZEL_SIDE + WINDOW_W + COL_GAP + COL_W + BEZEL_SIDE, SPEC)
CASE_H = P(BEZEL_TOP + WINDOW_H + BAND_GAP + BAND_H + BEZEL_BOTTOM, SPEC)

WALL_INSET = P(4.0, SPEC, "борта утоплены от кромки плит; ужато с 5")
PLATE_CORNER_R = P(6.0, SPEC, "скругление углов плит")
FINGER_LEN = P(10.0, SPEC, "длина шипа")
FINGER_FROM_EDGE = P(30.0, SPEC, "шипы в 30 мм от концов борта")

# Кернф — свойство СТАНКА, а не железа. Линейкой его не подтвердить: он
# снимается пробным купоном, который для того и выведен на лист.
KERF = P(0.15, MEAS, "рез на сторону — РАСЧЁТ, снимается купоном")
SLOT_W = P(T - 2 * KERF, SPEC, "паз уже шипа на два реза")

STANDOFF_D = P(3.2, SPEC, "отверстие под M3")

# ── глубина ────────────────────────────────────────────────────────────────
# Полость 25 — решение Николая 25.09.2026. Динамик 28 в неё не влезает
# целиком, и не должен: он заходит в ТОЛЩИНУ задней плиты на 3 мм через
# окно под магнит и кончается за 1 мм до её наружной грани.
#
#     передняя плита  0…4      динамик  4…32
#     полость         4…29     задняя плита  29…33
#
# Наружу ничего не торчит. Габарит 25 + 8 = 33 вместо 37.
#
# Высота борта = полость + 8: шипы проходят СКВОЗЬ обе плиты и кончаются
# вровень с наружными гранями, поэтому борт подписан наружным габаритом.
CAVITY = P(25.0, SPEC, "полость между плитами")
DEPTH = P(CAVITY + 2 * T, SPEC, "габарит по глубине = полость + два шипа")

# ── коробка бортов ─────────────────────────────────────────────────────────
BOX_W = P(CASE_W - 2 * WALL_INSET, SPEC, "длина верхнего и нижнего бортов")
BOX_H = P(CASE_H - 2 * WALL_INSET, SPEC)
RAIL_SIDE_L = P(BOX_H - 2 * T, SPEC, "боковые борта встают МЕЖДУ верхним и нижним")
SLOT_L_CLEAR = P(0.10, SPEC, "свободный ход шипа вдоль паза")
FINGER_EVERY = P(80.0, SPEC, "шаг расстановки шипов по длине борта")

# ── ножки ──────────────────────────────────────────────────────────────────
# Выступы по нижней кромке ОБЕИХ плит. Панель настенная, но так она ещё и
# стоит: две плиты разнесены на глубину корпуса, то есть опора выходит
# шириной во всю деталь и глубиной 28 мм — этого достаточно.
FOOT_PROUD = P(3.0, SPEC, "насколько ножка выступает ниже кромки плиты")
FOOT_W = P(30.0, SPEC, "ширина ножки")
FOOT_FROM_EDGE = P(40.0, SPEC, "от торца плиты до начала ножки")
FOOT_R = P(1.5, SPEC, "скругление наружных углов ножки")

# ── вентиляция: два ряда щелей вразбежку по верху задней плиты ─────────────
# Раскладка как на NickoScope32: щели одной ширины и двух длин, второй ряд
# сдвинут на полпериода, чтобы перемычки одного ряда стояли против середин
