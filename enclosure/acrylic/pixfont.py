# -*- coding: utf-8 -*-
"""
Шрифт 5x7 для надписей, набираемых ОТВЕРСТИЯМИ.

Точка = отверстие. Сетка та же, что у решётки спикера, поэтому буквы и
решётка читаются как одно пиксельное поле — по мотивам самой матрицы.

Только те знаки, что нужны для NickoScope и Matrix.
"""

GLYPHS = {
    "N": ["#...#", "##..#", "##..#", "#.#.#", "#..##", "#..##", "#...#"],
    "S": [".###.", "#...#", "#....", ".###.", "....#", "#...#", ".###."],
    "M": ["#...#", "##.##", "#.#.#", "#.#.#", "#...#", "#...#", "#...#"],
    "i": ["..#..", ".....", ".##..", "..#..", "..#..", "..#..", ".###."],
    "c": [".....", ".....", ".###.", "#...#", "#....", "#...#", ".###."],
    "k": ["#....", "#....", "#..#.", "#.#..", "##...", "#.#..", "#..#."],
    "o": [".....", ".....", ".###.", "#...#", "#...#", "#...#", ".###."],
    "p": [".....", ".....", "####.", "#...#", "####.", "#....", "#...."],
    "e": [".....", ".....", ".###.", "#...#", "#####", "#....", ".###."],
    "a": [".....", ".....", ".###.", "....#", ".####", "#...#", ".####"],
    "t": [".#...", ".#...", "###..", ".#...", ".#...", ".#..#", "..##."],
    "r": [".....", ".....", "#.##.", "##..#", "#....", "#....", "#...."],
    "x": [".....", ".....", "#...#", ".#.#.", "..#..", ".#.#.", "#...#"],
    " ": ["....."] * 7,
}
W, H, GAP = 5, 7, 1


def cells(text):
    """Занятые клетки строки: (колонка, ряд), ряд 0 — верхний."""
    out, col = [], 0
    for ch in text:
        g = GLYPHS.get(ch)
        if g is None:
            raise KeyError(f"нет знака {ch!r} — добавьте в GLYPHS")
        for r, row in enumerate(g):
            for c, v in enumerate(row):
                if v == "#":
                    out.append((col + c, r))
        col += W + GAP
    return out


def width(text):
    return len(text) * (W + GAP) - GAP


if __name__ == "__main__":
    for t in ("NickoScope", "Matrix"):
        print(f"{t!r}: {width(t)} колонок, {len(cells(t))} отверстий")
        pts = set(cells(t))
        for r in range(H):
            print("   " + "".join("O" if (c, r) in pts else " "
                                  for c in range(width(t))))


# ── минимальный шрифт 4x6 для одной строки под экраном ────────────────────
# Почему не 3 в ширину: при трёх колонках M и N становятся неотличимы —
# для обоих остаётся один и тот же рисунок «столбик, заполненный верх,
# столбик». А в строке есть и то и другое: NickoScope Matrix.
MINI = {
    "N": ["#..#", "##.#", "##.#", "#.##", "#.##", "#..#"],
    "S": [".###", "#...", ".##.", "...#", "...#", "###."],
    "M": ["#..#", "####", "####", "#..#", "#..#", "#..#"],
    "i": [".#..", "....", "##..", ".#..", ".#..", "###."],
    "c": ["....", "....", ".###", "#...", "#...", ".###"],
    "k": ["#...", "#..#", "#.#.", "##..", "#.#.", "#..#"],
    "o": ["....", "....", ".##.", "#..#", "#..#", ".##."],
    "p": ["....", "....", "###.", "#..#", "###.", "#..."],
    "e": ["....", "....", ".##.", "#.##", "#...", ".###"],
    "a": ["....", "....", ".##.", "...#", ".###", ".###"],
    "t": [".#..", ".#..", "###.", ".#..", ".#..", "..##"],
    "r": ["....", "....", "#.##", "##..", "#...", "#..."],
    "x": ["....", "....", "#..#", ".##.", ".##.", "#..#"],
}
MW, MH = 4, 6
WORD_GAP = 2          # между словами, вместо целого пустого знака


def mini_cells(words):
    """Занятые клетки одной строки из нескольких слов. Возвращает (клетки, ширина)."""
    out, col = [], 0
    for wi, w in enumerate(words):
        if wi:
            col += WORD_GAP
        for ch in w:
            g = MINI.get(ch)
            if g is None:
                raise KeyError(f"нет знака {ch!r} в MINI")
            for r, row in enumerate(g):
                for c, v in enumerate(row):
                    if v == "#":
                        out.append((col + c, r))
            col += MW + 1
        col -= 1
    return out, col


def mini_preview(words):
    pts, w = mini_cells(words)
    sp = set(pts)
    return "\n".join("".join("O" if (c, r) in sp else " " for c in range(w))
                     for r in range(MH)), w
