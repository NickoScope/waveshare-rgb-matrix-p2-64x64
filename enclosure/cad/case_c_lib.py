def measured_params():
    """Все параметры со статусом ОБМЕР — то, что запрещено замораживать."""
    out = []
    for name, val in sorted(globals().items()):
        if isinstance(val, P) and val.src == MEAS:
            out.append((name, val.value, val.note))
    return out


def fits_plate(length, width):
    """Ложится ли деталь на стол: плашмя либо по диагонали."""
    flat = length <= float(PLATE) and width <= float(PLATE)
    diag = (length + width) <= float(DIAG)
    return flat or diag, ("плашмя" if flat else ("по диагонали" if diag else "делить"))


