def min_depth(with_controller=True):
    """Наименьшая глубина корпуса для данной компоновки.

    Панель глубину НЕ определяет: монтажная рамка 15 мм доказывает, что вся
    электроника панели в эти 15 укладывается, и на неё уходит 2.5 + 15 + 2.0
    = 19.5. Определяет глубину плата контроллера, стоящая за панелью.
    """
    base = float(WALL_FRONT) + float(PANEL_T) + float(WALL_BACK)
    if not with_controller:
        return base + max(float(CONN_PROUD), float(VH4_PROUD)) + 0.5
    return base + max(float(CTRL_T),
                      max(float(CONN_PROUD), float(VH4_PROUD)) + 0.5)


def relief_depth():
    """На сколько прилив должен выйти за заднюю плоскость корпуса.

    Ноль, если выступающая часть разъёмов укладывается в полость за модулем —
    и при нынешних числах это так: прилив не нужен, крышка ровная. Функция
    оставлена, потому что до обмера это не факт: вырастет CONN_PROUD выше
    полости — прилив появится сам, и на листах он будет виден.
    """
    need = max(float(CONN_PROUD), float(VH4_PROUD)) + float(RELIEF_MARGIN)
    return max(0.0, need - float(CAVITY_BEHIND))


