def cover_points():
    """Точки притяжки крышки.

    Считаются НЕ от габарита плиты, а от кромки окна у матрицы. В плоскости
    лица свободной полки всего 7.1 мм — бобышка туда не встанет. Но фаска
    живёт только в толще плиты (2.5 мм), а глубже окно уже узкое, и между
    его кромкой и бортом остаётся около 12 мм. Бобышки растут с тыльной
    стороны плиты и попадают именно в эту зону.
    """
    ap_x = (float(FIELD_W) - 2 * float(OVERLAP)) / 2     # кромка окна у матрицы
    ap_y = (float(FIELD_H) - 2 * float(OVERLAP)) / 2
    in_x = float(CASE_W) / 2 - float(WALL_SIDE)          # внутренняя стенка борта
    in_y_top = float(CASE_H) / 2 - float(FIELD_CY) - float(WALL_SIDE)
    in_y_bot = -float(CASE_H) / 2 - float(FIELD_CY) + float(WALL_SIDE)

    hx = (ap_x + in_x) / 2
    hy_top = (ap_y + in_y_top) / 2
    hy_bot = in_y_bot + float(COVER_BOSS_D) / 2 + 1.0
    hy_mid = (hy_top + hy_bot) / 2
    # Восемь точек: четыре угла плюс середина каждой стороны. Углы работают
    # на две стороны сразу, поэтому на каждую сторону приходится по три винта.
    return [(-hx, hy_top), (0.0, hy_top), (hx, hy_top),
            (-hx, hy_mid), (hx, hy_mid),
            (-hx, hy_bot), (0.0, hy_bot), (hx, hy_bot)]


def cover_boss_clearance():
    """Запас бобышки до кромки окна и до борта — то, из-за чего точки и
    считаются так, как считаются. Возвращает (до окна, до борта)."""
    ap_x = (float(FIELD_W) - 2 * float(OVERLAP)) / 2
    in_x = float(CASE_W) / 2 - float(WALL_SIDE)
    hx = (ap_x + in_x) / 2
    r = float(COVER_BOSS_D) / 2
    return (hx - r - ap_x, in_x - (hx + r))


