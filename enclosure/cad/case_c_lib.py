# -*- coding: utf-8 -*-
"""
Корпус C «LED MATRIX» — параметрическая база (этап M1).

ПРАВИЛО ЭТОГО ФАЙЛА
Каждый размер несёт статус источника. Их три:

    ЧЕРТЁЖ   — прочитано из заводского DWG, координаты или проставленный размер
    ТЗ       — записано в техническом задании, решение заказчика или конструктора
    ОБМЕР    — предположение, подлежит замене после обмера железа

Ни одно значение со статусом ОБМЕР не имеет права попасть в печатный файл, пока
не заменено фактом. Проверка: verify.py печатает список всех ОБМЕР-параметров.

Система координат: X — ширина панели, Y — высота (вверх), Z — глубина,
считается ОТ ЛИЦА НАЗАД. Начало — центр активного поля.

    +X — вправо ДЛЯ ЗРИТЕЛЯ, стоящего перед панелью.

Тройка при этом левая (Z направлена от зрителя, а не на него). Так удобнее
считать глубину — матрица занимает Z от 2.5 до 17.5, а не отрицательные, —
но рендер вида с лица обязан зеркалить X, иначе право и лево меняются
местами. Это записано здесь, чтобы никто не «исправил» рендер обратно.
"""

from dataclasses import dataclass

MEAS = "ОБМЕР"
DWG = "ЧЕРТЁЖ"
SPEC = "ТЗ"


@dataclass(frozen=True)
class P:
    """Параметр со значением, единицей и происхождением."""
    value: float
    src: str
    note: str = ""

    def __float__(self):
        return float(self.value)


# --------------------------------------------------------------- матрица
# Габарит литой рамки: два проставленных размера 127.800 на чертеже.
PANEL_FRAME = P(127.8, DWG, "литая рамка, проставлено дважды")
# Кромка платы чертежом не размеряется. Паспорт даёт 128.
PANEL_BOARD = P(128.0, MEAS, "кромка платы; чертёж её не размеряет")
# Толщина: проставленного размера полной толщины на листе НЕТ.
# Габарит геометрии бокового вида 14.9996, дистрибьютор 14.5.
PANEL_T = P(15.0, MEAS, "справочно 14.5-15; полной толщины чертёж не размеряет")
# Ступень от лица до основной задней плоскости — проставлена и привязана.
PANEL_STEP = P(12.0, DWG, "от лицевой кромки бокового вида до задней плоскости")
PANEL_STEP2 = P(4.4775, DWG, "вторая ступень от лицевой кромки")

# Шесть точек M3 (слой SCREW), координаты от центра матрицы.
M3_POINTS = [(0.0, 56.85), (-56.85, 44.0), (56.85, 44.0),
             (-56.85, -44.0), (56.85, -44.0), (0.0, -56.85)]
M3_SRC = DWG
M3_PILOT = P(2.5, DWG, "⌀ пилотного отверстия под M3")

# Периметр: 28 отверстий ⌀4.0, отступы от контура 127.8.
PERIM_D = P(4.0, DWG)
PERIM_OFFSETS = [3.9, 23.9, 39.9, 59.9, 67.9, 87.9, 103.9, 123.9]

# Разъёмы: чертёж не размеряет ни посадочные места, ни высоты.
CONN_H = P(9.0, MEAS, "высота колодки HUB75 над задней плоскостью — не размерена")
VH4_H = P(7.0, MEAS, "высота колодки питания — не размерена")
# Считать надо не колодку, а колодку С НАДЕТЫМ ответным разъёмом: розетка IDC
# охватывает вилку сверху и добавляет к ней свою высоту. Это и есть размер,
# определяющий глубину корпуса.
CONN_STACK = P(16.0, MEAS, "колодка HUB75 с надетым шлейфом — ГЛАВНЫЙ размер на обмер")
VH4_STACK = P(12.0, MEAS, "колодка питания с надетым разъёмом")

# ---------------------------------------------------------- активное поле
PANELS_N = 2
FIELD_W = P(256.0, SPEC, "2 x 128 номинал; фактическое зависит от кромки платы")
FIELD_H = P(128.0, SPEC)
PITCH = P(2.0, SPEC, "шаг пикселя")

# ------------------------------------------------------------- контроллер
CTRL_W = P(50.0, SPEC, "Waveshare ESP32-S3-RGB-Matrix")
CTRL_H = P(42.0, SPEC)
CTRL_T = P(9.0, MEAS, "высота платы с надетыми разъёмами — не обмерена")

# ------------------------------------------------------------- габариты
DEPTH = P(30.0, SPEC, "рабочий габарит до обмера; цель 20 при утопленных колодках")
# ТЗ §4.3: минимальная стенка при белом филаменте — 2.0. Лицевая взята с запасом,
# потому что в ней прорезана фаска и остаточная толщина по кромке окна меньше.
WALL_FRONT = P(2.5, SPEC, "лицевая стенка; ТЗ §4.3 требует не менее 2.0")
WALL_BACK = P(2.0, SPEC, "задняя стенка")
WALL_SIDE = P(2.4, SPEC, "борт, 6 периметров по 0.4")
CAVITY_STRIP = P(float(DEPTH) - float(WALL_FRONT) - float(WALL_BACK), SPEC,
                 "полость в полосе: там матрицы нет")
CAVITY_BEHIND = P(float(DEPTH) - float(WALL_FRONT) - float(PANEL_T) - float(WALL_BACK),
                  SPEC, "полость за матрицей: колодки, шлейф, плата")

# Угол обзора матрицы ≥140°, то есть ±70° от нормали (ТЗ §4.2). Фаска обязана
# раскрываться не меньше этого, иначе кромка окна затенит крайний пиксель.
# ТЗ пишет «не менее 45°», но 45° этому углу не удовлетворяет: при стенке 2.5
# отступ был бы 2.5, а нужен 2.5*tg(70°).
VIEW_ANGLE = P(70.0, SPEC, "полуугол обзора из паспорта матрицы")
BEVEL_ANGLE = P(float(VIEW_ANGLE), SPEC, "фаска окна по углу обзора, не по минимуму ТЗ")
OVERLAP = P(0.5, SPEC, "перекрытие безелем активного поля, максимум по ТЗ")

from math import tan, radians
BEVEL_RUN = P(round(float(WALL_FRONT) * tan(radians(float(VIEW_ANGLE))), 2), SPEC,
              "раскрытие фаски по каждой стороне")

# Безель шире раскрытия фаски, чтобы осталась плоская лицевая полка.
BEZEL_TOP = P(14.0, SPEC, "рамка сверху; плоская полка = BEZEL - BEVEL_RUN")
BEZEL_SIDE = P(14.0, SPEC)
# ТЗ §4.4 считает высоту лица как «поле + полоса + верхняя и боковые рамки»:
# отдельной рамки под полосой нет, полоса сама доходит до нижней кромки.
BEZEL_BOTTOM = P(0.0, SPEC, "под полосой рамки нет, полоса доходит до кромки")
# ТЗ требует СВОБОДНУЮ полосу 20 мм. Фаска окна раскрывается во все стороны,
# в том числе вниз, и своё раскрытие отъедает у полосы. Поэтому конструктивная
# высота полосы = требуемая свободная плюс раскрытие фаски.
STRIP_FREE = P(20.0, SPEC, "свободная полоса по ТЗ §4.4 — то, что видно")
STRIP_H = P(round(float(STRIP_FREE) + float(BEVEL_RUN), 1), SPEC,
            "конструктивная: свободная плюс раскрытие фаски")

CASE_W = P(float(FIELD_W) + 2 * float(BEZEL_SIDE), SPEC)
CASE_H = P(float(BEZEL_TOP) + float(FIELD_H) + float(STRIP_H) + float(BEZEL_BOTTOM), SPEC)
# Поле не по центру лицевой плиты: снизу полоса, сверху её нет. Насколько
# центр плиты ниже центра поля.
FIELD_CY = P((float(STRIP_H) + float(BEZEL_BOTTOM) - float(BEZEL_TOP)) / 2.0, SPEC,
             "смещение центра плиты вниз относительно центра поля")

# ------------------------------------------------------- прилив под колодки
# Колодка с надетым шлейфом выше полости за матрицей, а точное место колодок
# чертёж не размеряет. Поэтому прилив сделан не локальным пятном, а полосой
# по всей ширине вдоль горизонтальной оси матриц: куда бы колодки ни попали
# на этой оси, они окажутся в приливе. После обмера полоса сожмётся в пятна.
RELIEF_BAND_Y = P(0.0, SPEC, "ось полосы прилива по Y = осевая матриц")
RELIEF_BAND_H = P(56.0, SPEC, "высота полосы; сузится после обмера")
RELIEF_MARGIN = P(1.5, SPEC, "запас над разъёмом")


def relief_depth():
    """На сколько прилив должен выйти за заднюю плоскость корпуса."""
    need = max(float(CONN_STACK), float(VH4_STACK)) + float(RELIEF_MARGIN)
    return max(0.0, need - float(CAVITY_BEHIND))


