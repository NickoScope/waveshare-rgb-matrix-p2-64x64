def seat_nominal():
    """Номинал гнезда — по большему из двух кандидатов, иначе платы не войдут."""
    big = max(float(PANEL_BOARD), float(PANEL_FRAME))
    return 2 * big, big


def seat_bounds():
    """Границы гнезда (x0, x1, y0, y1), симметрично относительно центра поля."""
    w, h = seat_nominal()
    g = float(SEAT_GAP)
    return -w / 2 - g, w / 2 + g, -h / 2 - g, h / 2 + g


# Где стоят прижимные языки. Один список на две детали: крышка их строит,
# корпус вырезает под них проёмы в рёбрах гнезда, чтобы язык прошёл насквозь.
CLAMP_AT_Y = (-34.0, 34.0)      # языки на левом и правом рёбрах
CLAMP_AT_X = (-70.0, 70.0)      # языки на верхнем и нижнем рёбрах


def clamp_positions():
    """Список (x, y, горизонтальный ли язык, знак наружу)."""
    x0, x1, y0, y1 = seat_bounds()
    out = []
    for cy in CLAMP_AT_Y:
        out.append((x0, cy, True, -1))
        out.append((x1, cy, True, +1))
    for cx in CLAMP_AT_X:
        out.append((cx, y1, False, +1))
        out.append((cx, y0, False, -1))
    return out


def overlap_after_centering():
    """Перекрытие безелем на сторону для обоих кандидатов — то, ради чего
    прижим и ведётся к центру. Возвращает {ширина полотна: перекрытие}."""
    ap_x = (float(FIELD_W) - 2 * float(OVERLAP)) / 2
    out = {}
    for cand in (float(PANEL_BOARD), float(PANEL_FRAME)):
        out[2 * cand] = cand - ap_x
    return out


