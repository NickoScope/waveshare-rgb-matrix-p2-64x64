def corner_joints():
    """Оси угловых стяжек: (x, знак по Y — к какому шву прилив примыкает).

    Прилив прижат к внутренней поверхности борта: иначе он повиснет в
    полости. И не должен доставать до гнезда панели, иначе упрётся в неё.
    """
    x = float(CASE_W) / 2 - float(WALL_SIDE) - float(JOINT_BOSS) / 2
    return [(sx * x, sy) for sx in (-1, 1) for sy in (-1, 1)]


def joint_clearance():
    """Зазор между угловым приливом и гнездом панели."""
    x = float(CASE_W) / 2 - float(WALL_SIDE) - float(JOINT_BOSS) / 2
    inner_edge = x - float(JOINT_BOSS) / 2
    return inner_edge - seat_bounds()[1]


